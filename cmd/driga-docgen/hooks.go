package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/pelletier/go-toml/v2"

	"github.com/labstack/driga/internal/hooks"
)

// hookEvent is one installed hook as the installer would write it.
type hookEvent struct {
	Event   string
	Timeout string
}

// installedHooks runs each installer in dry-run mode against an empty file in
// a temporary directory and reads the events back out of the proposed
// contents. Nothing outside that directory is read or written, and the page
// lists what the installer would actually write rather than a copy of its
// event list.
func installedHooks() (claude, codex, copilot []hookEvent, err error) {
	dir, err := os.MkdirTemp("", "driga-docgen-hooks-")
	if err != nil {
		return nil, nil, nil, err
	}
	defer os.RemoveAll(dir)
	const bin = "/usr/local/bin/driga"
	epoch := time.Unix(0, 0)

	d, err := hooks.ClaudeInstall(filepath.Join(dir, "settings.json"), bin, true, epoch)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("claude: %w", err)
	}
	var claudeFile struct {
		Hooks map[string][]struct {
			Hooks []struct {
				Timeout int `json:"timeout"`
			} `json:"hooks"`
		} `json:"hooks"`
	}
	if err := json.Unmarshal([]byte(d.After), &claudeFile); err != nil {
		return nil, nil, nil, fmt.Errorf("claude: %w", err)
	}
	for event, groups := range claudeFile.Hooks {
		timeout := 0
		for _, g := range groups {
			for _, h := range g.Hooks {
				timeout = max(timeout, h.Timeout)
			}
		}
		claude = append(claude, hookEvent{event, seconds(timeout, "agent default")})
	}

	d, err = hooks.CodexInstall(filepath.Join(dir, "config.toml"), bin, true, epoch)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("codex: %w", err)
	}
	var codexFile struct {
		Hooks map[string][]struct {
			Hooks []struct {
				Timeout int `toml:"timeout"`
			} `toml:"hooks"`
		} `toml:"hooks"`
	}
	if err := toml.Unmarshal([]byte(d.After), &codexFile); err != nil {
		return nil, nil, nil, fmt.Errorf("codex: %w", err)
	}
	for event, groups := range codexFile.Hooks {
		timeout := 0
		for _, g := range groups {
			for _, h := range g.Hooks {
				timeout = max(timeout, h.Timeout)
			}
		}
		codex = append(codex, hookEvent{event, seconds(timeout, "agent default")})
	}

	d, err = hooks.CopilotInstall(filepath.Join(dir, "driga.json"), bin, true, epoch)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("copilot: %w", err)
	}
	var copilotFile struct {
		Hooks map[string][]struct {
			TimeoutSec int `json:"timeoutSec"`
		} `json:"hooks"`
	}
	if err := json.Unmarshal([]byte(d.After), &copilotFile); err != nil {
		return nil, nil, nil, fmt.Errorf("copilot: %w", err)
	}
	for event, entries := range copilotFile.Hooks {
		timeout := 0
		for _, e := range entries {
			timeout = max(timeout, e.TimeoutSec)
		}
		copilot = append(copilot, hookEvent{event, seconds(timeout, "agent default")})
	}

	for _, list := range [][]hookEvent{claude, codex, copilot} {
		if len(list) == 0 {
			return nil, nil, nil, fmt.Errorf("an installer proposed no hook events")
		}
		sort.Slice(list, func(i, j int) bool { return strings.ToLower(list[i].Event) < strings.ToLower(list[j].Event) })
	}
	return claude, codex, copilot, nil
}

func seconds(n int, fallback string) string {
	if n == 0 {
		return fallback
	}
	return fmt.Sprintf("%d s", n)
}

func renderHooks() (string, error) {
	claude, codex, copilot, err := installedHooks()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	frontmatter(&b,
		"Hooks",
		"Which agent hook events `driga hooks install` writes for Claude Code, Codex and Copilot, with timeouts.",
		"The hook events driga installs per agent and their timeouts, generated by running each installer in dry-run mode.",
		"You want to know exactly what `driga hooks install` adds to an agent's configuration.",
		"You are reviewing a hooks diff before accepting it.",
	)
	b.WriteString("Hooks are optional. Without them Driga still reads session files and the\n")
	b.WriteString("process table; hooks add lifecycle and attention events, Claude prompt\n")
	b.WriteString("answering and Copilot session state. Every install shows a unified diff and asks before\n")
	b.WriteString("writing, backs up edited files to `*.driga-bak-<timestamp>`, and uninstall\n")
	b.WriteString("removes only Driga's own entries. A hook always exits successfully and\n")
	b.WriteString("prints nothing, so a failing hook never blocks the agent.\n\n")
	b.WriteString("Each hook runs `driga hook <adapter> <event>`. The tables below are produced\n")
	b.WriteString("by running each installer against an empty configuration, so they list what\n")
	b.WriteString("the installer writes.\n\n")
	b.WriteString("```sh\ndriga hooks install --dry-run   # preview every adapter\ndriga hooks install claude      # or codex, copilot, all\ndriga hooks status\ndriga hooks uninstall\n```\n\n")

	section := func(title, file, note string, events []hookEvent) {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", title, note)
		fmt.Fprintf(&b, "Written to %s.\n\n", file)
		b.WriteString("| Event | Timeout |\n|---|---|\n")
		for _, e := range events {
			fmt.Fprintf(&b, "| %s | %s |\n", code(e.Event), e.Timeout)
		}
		b.WriteString("\n")
	}
	section("Claude Code", "`~/.claude/settings.json` (or under `CLAUDE_CONFIG_DIR`), appended beside existing hooks",
		"`PermissionRequest` lets Driga answer permission prompts; its long timeout keeps the prompt open while you decide. The other events record lifecycle and attention.",
		claude)
	section("Codex", "a marked block in `~/.codex/config.toml` (or `$CODEX_HOME/config.toml`), preserving comments and existing `notify` settings",
		"Codex reports permission requests to Driga. Driga does not answer Codex prompts.",
		codex)
	section("GitHub Copilot CLI", "Driga's own file, `~/.copilot/hooks/driga.json` (or under `COPILOT_HOME`); uninstall deletes only that file",
		"Copilot session state comes only from hooks and the process table. Restart running Copilot sessions after installing or removing hooks.",
		copilot)
	b.WriteString("## Gemini CLI\n\n")
	b.WriteString("Driga installs no Gemini hooks. Gemini sessions are read from their chat\n")
	b.WriteString("transcripts.\n")
	return b.String(), nil
}
