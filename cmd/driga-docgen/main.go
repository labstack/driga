// Command driga-docgen writes the generated half of the documentation site.
//
// Every reference surface it documents is already enumerated in Go: the Kong
// command tree behind `driga --help`, the settings table behind .env.example,
// the MCP server's own tools/list answer, and the hook installers. Writing them
// again by hand would create a second source that can disagree with the first,
// so this program is the only writer of the pages under
// site/src/content/docs/reference/ that carry the generated marker.
//
// Run `just docs` to rewrite the pages and `just docs-check` (part of
// `just check`) to fail when a committed page is behind the code. Edit this
// generator, never the pages.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// MDX parses HTML comments as JSX, so the marker uses the MDX comment form.
const generatedMarker = "{/* Generated by cmd/driga-docgen. Do not edit by hand; run `just docs` to regenerate. */}"

func main() {
	var (
		out   string
		check bool
	)
	flag.StringVar(&out, "out", "site/src/content/docs/reference", "directory to write generated reference pages into")
	flag.BoolVar(&check, "check", false, "fail if the pages on disk differ from what would be generated")
	flag.Parse()

	if err := run(out, check, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "driga-docgen:", err)
		os.Exit(1)
	}
}

func run(out string, check bool, stdout io.Writer) error {
	pages, err := generate()
	if err != nil {
		return err
	}
	if check {
		if err := verify(out, pages); err != nil {
			return err
		}
		fmt.Fprintf(stdout, "driga-docgen: %d generated page(s) match the code\n", len(pages))
		return nil
	}
	if err := write(out, pages); err != nil {
		return err
	}
	fmt.Fprintf(stdout, "driga-docgen: wrote %d page(s) to %s\n", len(pages), out)
	return nil
}

// generate renders every page, keyed by file name relative to the reference
// directory.
func generate() (map[string]string, error) {
	pages := map[string]string{}
	cli, err := renderCLI()
	if err != nil {
		return nil, fmt.Errorf("cli reference: %w", err)
	}
	pages["cli.mdx"] = cli
	pages["settings.mdx"] = renderSettings()
	tools, err := renderMCP()
	if err != nil {
		return nil, fmt.Errorf("mcp reference: %w", err)
	}
	pages["mcp-tools.mdx"] = tools
	hooks, err := renderHooks()
	if err != nil {
		return nil, fmt.Errorf("hooks reference: %w", err)
	}
	pages["hooks.mdx"] = hooks
	for name, body := range pages {
		if !strings.Contains(body, generatedMarker) {
			return nil, fmt.Errorf("%s is missing the generated marker", name)
		}
	}
	return pages, nil
}

func write(out string, pages map[string]string) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	for name, body := range pages {
		if err := os.WriteFile(filepath.Join(out, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	orphans, err := orphaned(out, pages)
	if err != nil {
		return err
	}
	for _, path := range orphans {
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}

// verify compares in both directions: a page that differs or is missing, and a
// marked page that no generator produces any more.
func verify(out string, pages map[string]string) error {
	var stale []string
	for name, body := range pages {
		path := filepath.Join(out, name)
		existing, err := os.ReadFile(path)
		if err != nil {
			stale = append(stale, path+" (missing)")
			continue
		}
		if !bytes.Equal(existing, []byte(body)) {
			stale = append(stale, path)
		}
	}
	orphans, err := orphaned(out, pages)
	if err != nil {
		return err
	}
	for _, path := range orphans {
		stale = append(stale, path+" (no longer generated)")
	}
	if len(stale) == 0 {
		return nil
	}
	sort.Strings(stale)
	return fmt.Errorf("generated reference pages are out of date:\n  %s\nrun `just docs` (go run ./cmd/driga-docgen) and commit the result",
		strings.Join(stale, "\n  "))
}

// orphaned lists marked pages in out that the current generator does not
// produce. Hand-written pages carry no marker and are never touched.
func orphaned(out string, pages map[string]string) ([]string, error) {
	entries, err := os.ReadDir(out)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var orphans []string
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".mdx") {
			continue
		}
		if _, ok := pages[entry.Name()]; ok {
			continue
		}
		path := filepath.Join(out, entry.Name())
		body, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		if bytes.Contains(body, []byte(generatedMarker)) {
			orphans = append(orphans, path)
		}
	}
	sort.Strings(orphans)
	return orphans, nil
}

// frontmatter writes the shared page header. Values are JSON-quoted, which is
// valid YAML for any string.
func frontmatter(b *strings.Builder, title, description, summary string, readWhen ...string) {
	b.WriteString("---\n")
	fmt.Fprintf(b, "title: %s\n", quote(title))
	fmt.Fprintf(b, "description: %s\n", quote(description))
	fmt.Fprintf(b, "summary: %s\n", quote(summary))
	if len(readWhen) > 0 {
		b.WriteString("read_when:\n")
		for _, when := range readWhen {
			fmt.Fprintf(b, "  - %s\n", quote(when))
		}
	}
	b.WriteString("generated: true\n")
	b.WriteString("---\n\n")
	b.WriteString(generatedMarker + "\n\n")
}

func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)
	return `"` + r.Replace(s) + `"`
}

// text escapes prose for MDX: braces open expressions and angle brackets open
// JSX, so both are written as literals. Backticked spans are left alone because
// MDX treats code as literal text.
func text(s string) string {
	var b strings.Builder
	inCode := false
	for _, r := range s {
		if r == '`' {
			inCode = !inCode
			b.WriteRune(r)
			continue
		}
		if inCode {
			b.WriteRune(r)
			continue
		}
		switch r {
		case '{':
			b.WriteString(`\{`)
		case '}':
			b.WriteString(`\}`)
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '*':
			b.WriteString(`\*`)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// cell escapes prose for a GFM table cell.
func cell(s string) string {
	s = strings.ReplaceAll(text(s), "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

// code renders a literal as inline code, safe inside a table cell. A literal
// containing a backtick is fenced with two.
func code(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

func plural(n int, word string) string {
	if n == 1 {
		return fmt.Sprintf("%d %s", n, word)
	}
	return fmt.Sprintf("%d %ss", n, word)
}
